export function compressOf(level: number) {
  return [0, 0.17, 0.33, 0.47, 0.59, 0.71][level] ?? 0;
}

export function slingSpeed(level: number) {
  return [1180, 1320, 1460, 1600, 1760][level] ?? 1180;
}

export function fareMult(level: number) {
  return 1 + level * 0.18;
}

export function delayBonus(level: number) {
  return level * 0.4;
}

export function carFriction(level: number) {
  return [0.968, 0.978, 0.986, 0.992][level] ?? 0.968;
}

export function won(n: number) {
  return "$" + Math.round(n).toLocaleString("en-US");
}

export function rankTitle(n: number) {
  if (n >= 32) return "Compressor Saint";
  if (n >= 24) return "Capacity Whisperer";
  if (n >= 18) return "Rush Hour Regular";
  if (n >= 12) return "Clock Thief";
  if (n >= 6) return "Overflow Hunter";
  return "Aspiring Dispatcher";
}

export function starsFor(occupancy: number, boss: boolean, broken: boolean) {
  if (boss && !broken) return 0;
  if (occupancy >= 200) return 3;
  if (occupancy >= 150) return 2;
  if (occupancy >= 100) return 1;
  return 0;
}

export function stationById(id: string) {
  return STATIONS.find((s) => s.id === id) ?? STATIONS[0];
}